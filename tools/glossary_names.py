"""glossary_names.py: (re)write glossary.md's generated section from the translated name tables.

    python -X utf8 tools/glossary_names.py

Every translated FE name (parts, attacks, weapon kinds, items, status words, tutorial topics) whose JP occurs in
some FF string, as a whole kana/kanji run of 3+ characters or inside 「」, becomes a glossary row, so dialogue that
mentions an item or attack uses the same English as the menu. Names already in a hand-written table are skipped.
The section sits between the GENERATED markers; everything else in glossary.md is left alone.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import batches  # noqa: E402

TABLES = {"466688": "attack", "46A508": "weapon kind", "468A00": "part", "50C998": "item", "46F0BC": "status",
          "50EF18": "tutorial topic"}
BEGIN, END = "<!-- GENERATED by tools/glossary_names.py -->", "<!-- END GENERATED -->"


def main():
    hand = {j for jps, _, _ in batches.glossary() for j in jps}
    text = batches.GLOSSARY.read_text(encoding="utf-8")
    if BEGIN in text:
        hand = {j for jps, _, _ in batches.glossary() for j in jps} - set(
            re.findall(r"^\| ([^|]+?) \|", text.split(BEGIN)[1].split(END)[0], re.M))
    ff, names = [], {}
    for _, doc, entries in batches.docs():
        for e in entries:
            plain = batches.TOKEN.sub("", e["jp"])
            if e["kind"] == "ff":
                ff.append(plain)
            elif doc["table"] in TABLES and e.get("en") and plain and plain not in hand:
                names.setdefault(plain, (batches.TOKEN.sub("", e["en"]), TABLES[doc["table"]]))
    alltext = "\n".join(ff)
    quoted = " ".join(re.findall(r"「([^」]*)」", alltext))
    rows = []
    for jp, (en, what) in sorted(names.items()):
        if jp == "ダミー" or "|" in jp + en:
            continue
        if (len(jp) >= 3 and batches.has_term(alltext, jp)) or batches.has_term(quoted, jp):
            rows.append(f"| {jp} | {en} | | {what} | |")
    section = (f"{BEGIN}\n## Game names (generated from the translated name tables; edit the tables, then re-run)\n"
               "| JP | EN | max | notes | Avoid |\n|---|---|---|---|---|\n" + "\n".join(rows) + f"\n{END}\n")
    if BEGIN in text:
        text = text.split(BEGIN)[0] + section + text.split(END, 1)[1].lstrip("\n")
    else:
        text = text.replace("## Decisions from earlier batches", section + "\n## Decisions from earlier batches")
    batches.GLOSSARY.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rows)} generated glossary rows")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
